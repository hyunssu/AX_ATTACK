BEGIN;

CREATE TABLE IF NOT EXISTS public.screen_owners_kyj (
    screen_number TEXT PRIMARY KEY,
    country TEXT NOT NULL,
    owner_team TEXT NOT NULL,
    owner_name TEXT NOT NULL,
    note TEXT,
    updated_by TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (btrim(screen_number) <> ''),
    CHECK (btrim(owner_name) <> '')
);

CREATE TABLE IF NOT EXISTS public.screen_owner_changes_kyj (
    id BIGSERIAL PRIMARY KEY,
    screen_number TEXT NOT NULL
        REFERENCES public.screen_owners_kyj(screen_number) ON DELETE RESTRICT,
    old_owner_name TEXT NOT NULL,
    new_owner_name TEXT NOT NULL,
    changed_by TEXT NOT NULL,
    source_room_id INTEGER
        REFERENCES public.chat_rooms_kyj(id) ON DELETE SET NULL,
    request_text TEXT NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (old_owner_name <> new_owner_name)
);

CREATE INDEX IF NOT EXISTS screen_owners_kyj_owner_name_idx
    ON public.screen_owners_kyj (owner_name);
CREATE INDEX IF NOT EXISTS screen_owners_kyj_country_team_idx
    ON public.screen_owners_kyj (country, owner_team);
CREATE INDEX IF NOT EXISTS screen_owner_changes_kyj_screen_changed_idx
    ON public.screen_owner_changes_kyj (screen_number, changed_at DESC);

